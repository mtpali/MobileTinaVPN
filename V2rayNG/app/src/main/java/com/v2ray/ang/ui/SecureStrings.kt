    fun a(n: Int): String {
        require(n in p.indices)
        val slot = p[n]
        val seed = ByteArray(32) { i ->
            (
                x[i] xor
                    y[(i * 7 + 5) and 31] xor
                    z[(i * 13 + 9) and 31] xor
                    ((i * 29 + slot * 17 + 0xa5) and 0xff)
                ).toByte()
        }
        val appId = BuildConfig.APPLICATION_ID.removeSuffix(".fdroid").toByteArray(Charsets.UTF_8)
        val key = try {
            val mac = Mac.getInstance("HmacSHA256")
            mac.init(SecretKeySpec(seed, "HmacSHA256"))
            mac.update(appId)
            mac.update((slot xor 0x6b).toByte())
            mac.update((n * 31 + 0x21).toByte())
            mac.doFinal()
        } finally {
            seed.fill(0)
            appId.fill(0)
        }

        val left = g[slot]
        val right = h[slot]
        check(left.size == right.size && left.size > 28)
        val packed = ByteArray(left.size) { i ->
            (
                left[i] xor
                    right[i] xor
                    ((0x37 + slot * 41 + i * 23) and 0xff)
                ).toByte()
        }

        return try {
            val cipher = Cipher.getInstance("AES/GCM/NoPadding")
            cipher.init(
                Cipher.DECRYPT_MODE,
                SecretKeySpec(key, "AES"),
                GCMParameterSpec(128, packed.copyOfRange(0, 12))
            )
            val plain = cipher.doFinal(packed.copyOfRange(12, packed.size))
            try {
                String(plain, Charsets.UTF_8)
            } finally {
                plain.fill(0)
            }
        } finally {
            key.fill(0)
            packed.fill(0)
        }
    }
